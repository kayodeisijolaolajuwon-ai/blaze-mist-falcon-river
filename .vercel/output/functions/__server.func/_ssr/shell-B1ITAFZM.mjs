function formatDate(iso) {
	const [y, m, d] = iso.split("-").map(Number);
	return new Date(Date.UTC(y, (m ?? 1) - 1, d ?? 1)).toLocaleDateString("en-GB", {
		day: "numeric",
		month: "long",
		year: "numeric",
		timeZone: "UTC"
	});
}
function slugify(title) {
	return title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "").slice(0, 60) || "note";
}
var useLedger = create()(persist((set, get) => ({
	posts: seedPosts,
	tier: "none",
	memberName: "",
	members: 186,
	patrons: 24,
	subscribe: (tier, name) => set((state) => {
		let members = state.members;
		let patrons = state.patrons;
		if (state.tier === "member") members -= 1;
		if (state.tier === "patron") patrons -= 1;
		if (tier === "member") members += 1;
		if (tier === "patron") patrons += 1;
		return {
			tier,
			memberName: name.trim(),
			members: Math.max(0, members),
			patrons: Math.max(0, patrons)
		};
	}),
	cancel: () => set((state) => ({
		tier: "none",
		memberName: "",
		members: state.tier === "member" ? Math.max(0, state.members - 1) : state.members,
		patrons: state.tier === "patron" ? Math.max(0, state.patrons - 1) : state.patrons
	})),
	publish: (input) => {
		const slugBase = slugify(input.title);
		const taken = new Set(get().posts.map((p) => p.slug));
		let slug = slugBase;
		let n = 2;
		while (taken.has(slug)) {
			slug = `${slugBase}-${n}`;
			n += 1;
		}
		const paragraphs = input.body.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
		const words = paragraphs.join(" ").split(/\s+/).filter(Boolean).length;
		const post = {
			id: `local-${Date.now()}`,
			slug,
			title: input.title.trim(),
			dek: input.dek.trim(),
			category: input.category.trim() || "Notes",
			minutes: Math.max(2, Math.round(words / 180)),
			publishedAt: (/* @__PURE__ */ new Date()).toISOString().slice(0, 10),
			access: input.access,
			cover: COVERS[get().posts.length % COVERS.length] ?? COVERS[0],
			body: paragraphs
		};
		set((state) => ({ posts: [post, ...state.posts] }));
		return slug;
	},
	removePost: (id) => set((state) => ({ posts: state.posts.filter((p) => p.id !== id) }))
}), { name: "hearth-ledger" }));
